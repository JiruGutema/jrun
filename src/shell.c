static const char *BASH_COMPLETION_COMMAND =
"# Completes the command after the target: resolves the target, then runs the\n"
"# completion for word $1 onwards of the line from inside that directory.\n"
"__jrun_complete_command() {\n"
"    local target=\"$1\" start=\"$2\" cur=\"${COMP_WORDS[COMP_CWORD]}\"\n"
"    local __jrun_dir\n"
"    __jrun_dir=$(command jrun --resolve \"$target\" 2>/dev/null) || return 0\n"
"    [ -d \"$__jrun_dir\" ] || return 0\n"
"\n"
"    # If Ctrl-C lands mid-completion the cd back below never runs;\n"
"    # __jrun_track sees this at the next prompt and puts the shell back.\n"
"    __jrun_completing_from=\"$PWD\"\n"
"    local __jrun_oldpwd=\"$OLDPWD\"\n"
"    builtin cd -- \"$__jrun_dir\" 2>/dev/null || { __jrun_completing_from=; return 0; }\n"
"\n"
"    local __jrun_offset=\n"
"    if declare -F _comp_command_offset >/dev/null; then\n"
"        __jrun_offset=_comp_command_offset\n"
"    elif declare -F _command_offset >/dev/null; then\n"
"        __jrun_offset=_command_offset\n"
"    fi\n"
"\n"
"    if [ -n \"$__jrun_offset\" ]; then\n"
"        \"$__jrun_offset\" \"$start\"\n"
"    elif [ \"$COMP_CWORD\" -eq \"$start\" ]; then\n"
"        mapfile -t COMPREPLY < <(compgen -c -- \"$cur\")\n"
"    else\n"
"        compopt -o filenames 2>/dev/null\n"
"        mapfile -t COMPREPLY < <(compgen -f -- \"$cur\")\n"
"    fi\n"
"\n"
"    # ble.sh hooks the offset function and takes the candidates out of\n"
"    # COMPREPLY itself, while we are still in the right directory, falling back\n"
"    # to files there when there are none. It leaves COMPREPLY empty, so the\n"
"    # fixes below would only mix in files that do not belong.\n"
"    if [ -n \"$__jrun_offset\" ] && [ -n \"${BLE_ATTACHED-}\" ] &&\n"
"       declare -F \"ble/function#advice/after:$__jrun_offset\" >/dev/null; then\n"
"        :\n"
"    else\n"
"        # Anything readline does after we return happens back in the original\n"
"        # directory. Commands without a completion spec of their own (nvim,\n"
"        # say) ask for readline's default file completion, so do that here.\n"
"        local __jrun_opts\n"
"        __jrun_opts=$(compopt 2>/dev/null)\n"
"        if [ \"${#COMPREPLY[@]}\" -eq 0 ] && [ \"$COMP_CWORD\" -gt \"$start\" ] &&\n"
"           [[ \"$__jrun_opts\" == *\"-o default\"* || \"$__jrun_opts\" == *\"-o bashdefault\"* ]]; then\n"
"            compopt +o default +o bashdefault -o filenames 2>/dev/null\n"
"            __jrun_opts=\"-o filenames\"\n"
"            mapfile -t COMPREPLY < <(compgen -f -- \"$cur\")\n"
"        fi\n"
"\n"
"        # Readline also adds the \"/\" after a directory, so settle a lone match.\n"
"        if [ \"${#COMPREPLY[@]}\" -eq 1 ] && [ -d \"${COMPREPLY[0]}\" ] &&\n"
"           [ \"${COMPREPLY[0]%/}\" = \"${COMPREPLY[0]}\" ] &&\n"
"           [[ \"$__jrun_opts\" == *\"-o filenames\"* ]]; then\n"
"            COMPREPLY[0]=\"${COMPREPLY[0]}/\"\n"
"            compopt -o nospace 2>/dev/null\n"
"        fi\n"
"    fi\n"
"\n"
"    builtin cd -- \"$__jrun_completing_from\" 2>/dev/null\n"
"    OLDPWD=\"$__jrun_oldpwd\"\n"
"    __jrun_completing_from=\n"
"    return 0\n"
"}\n"
"\n";

