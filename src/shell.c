static const char *FISH_COMPLETION =
"\n"
"# Tab completion for jrun and j. The first word completes to directory names\n"
"# jrun knows about. Everything after it is completed as its own command line\n"
"# from inside the resolved directory, so `jrun api git ch<Tab>` offers api's\n"
"# branches and `jrun ~ nvim .ba<Tab>` offers files in $HOME.\n"
"function __jrun_complete_target\n"
"    switch \"$argv[1]\"\n"
"        case '-*'\n"
"            printf '%s\\n' --help --version --debug --quiet --interactive --yes --cd --init\n"
"        case '/*' '~*' . .. './*' '../*' '*/*'\n"
"            __fish_complete_directories \"$argv[1]\"\n"
"        case '*'\n"
"            command jrun --complete-target \"$argv[1]\" 2>/dev/null\n"
"    end\n"
"end\n"
"\n"
"function __jrun_complete\n"
"    set -l tokens (commandline -opc)\n"
"    set -l cur (commandline -ct)\n"
"    set -e tokens[1]\n"
"    while set -q tokens[1]; and contains -- $tokens[1] -d --debug -q --quiet -i --interactive -y --yes\n"
"        set -e tokens[1]\n"
"    end\n"
"\n"
"    if not set -q tokens[1]\n"
"        __jrun_complete_target \"$cur\"\n"
"        return\n"
"    end\n"
"\n"
"    set -l target $tokens[1]\n"
"    set -e tokens[1]\n"
"    set -l argn (math (count $tokens) + 1)\n"
"    switch $target\n"
"        case add remove\n"
"            test $argn -eq 1; and __fish_complete_directories \"$cur\"\n"
"            return\n"
"        case root\n"
"            if test $argn -eq 1\n"
"                printf '%s\\n' list add remove\n"
"            else if test $argn -eq 2 -a \"$tokens[1]\" != list\n"
"                __fish_complete_directories \"$cur\"\n"
"            end\n"
"            return\n"
"        case config\n"
"            test $argn -eq 1; and printf '%s\\n' show edit\n"
"            return\n"
"        case --init shell\n"
"            test $argn -eq 1; and printf '%s\\n' bash zsh fish\n"
"            return\n"
"        case cd --cd query\n"
"            test $argn -eq 1; and __jrun_complete_target \"$cur\"\n"
"            return\n"
"        case list prune reindex doctor help version -h --help -v --version\n"
"            return\n"
"    end\n"
"\n"
"    if test \"$tokens[1]\" = --\n"
"        set -e tokens[1]\n"
"    end\n"
"\n"
"    set -l dir (command jrun --resolve $target 2>/dev/null)\n"
"    or return\n"
"    test -d \"$dir\"; or return\n"
"\n"
"    # __jrun_completing keeps the PWD hook from recording this visit.\n"
"    set -l oldpwd $PWD\n"
"    set -g __jrun_completing 1\n"
"    if builtin cd $dir 2>/dev/null\n"
"        complete -C (string join ' ' -- (string escape -- $tokens) \"$cur\")\n"
"        builtin cd $oldpwd\n"
"    end\n"
"    set -e __jrun_completing\n"
"end\n"
"\n"
"complete -c jrun -f -k -a '(__jrun_complete)'\n";


bool shell_generate_init(Shell_Type shell)
{
    switch (shell) {
    case SHELL_BASH:
        printf("%s%s%s%s%s", BASH_HOOK, COMMON_POSIX_WRAPPER, BASH_COMPLETION_HELPERS,
               BASH_COMPLETION_COMMAND, BASH_COMPLETION_MAIN);
        return true;
    case SHELL_ZSH:
        printf("%s%s%s%s", ZSH_HOOK, COMMON_POSIX_WRAPPER, ZSH_COMPLETION_HELPERS,
               ZSH_COMPLETION_MAIN);
        return true;
    case SHELL_FISH:
        printf("%s%s", FISH_INIT, FISH_COMPLETION);
        return true;
    case SHELL_UNKNOWN:
    default:
        jrun_log_error("unsupported shell. Supported shells: bash, zsh, fish");
        return false;
    }
}
