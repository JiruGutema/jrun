"\n"
"# zsh decides whether a file match is a directory, and so whether to add a\n"
"# \"/\", when the match is inserted, which is after _jrun has cd'd back. compadd\n"
"# -W names the directory those tests run against, so point it at the real one.\n"
"# Variables are prefixed because compadd reads -a/-d/-O arrays by name from\n"
"# its caller's scope, and a local here could shadow one.\n"
"__jrun_compadd() {\n"
"    local -a __jrun_args\n"
"    local __jrun_a __jrun_file=0 __jrun_seen_w=0\n"
"    while (( $# )); do\n"
"        __jrun_a=$1\n"
"        shift\n"
"        case $__jrun_a in\n"
"            -W)\n"
"                __jrun_seen_w=1\n"
"                [[ $1 == /* ]] || 1=\"$__jrun_comp_dir/$1\"\n"
"                __jrun_args+=(-W \"$1\")\n"
"                shift\n"
"                ;;\n"
"            -W?*)\n"
"                __jrun_seen_w=1\n"
"                __jrun_a=${__jrun_a#-W}\n"
"                [[ $__jrun_a == /* ]] || __jrun_a=\"$__jrun_comp_dir/$__jrun_a\"\n"
"                __jrun_args+=(-W \"$__jrun_a\")\n"
"                ;;\n"
"            -|--)\n"
"                __jrun_args+=(\"$__jrun_a\" \"$@\")\n"
"                break\n"
"                ;;\n"
"            -[!-]*f*)\n"
"                __jrun_file=1\n"
"                __jrun_args+=(\"$__jrun_a\")\n"
"                ;;\n"
"            *)\n"
"                __jrun_args+=(\"$__jrun_a\")\n"
"                ;;\n"
"        esac\n"
"    done\n"
"    if (( __jrun_file && ! __jrun_seen_w )); then\n"
"        __jrun_args=(-W \"$__jrun_comp_dir/\" \"${__jrun_args[@]}\")\n"
"    fi\n"
"    if (( $+functions[__jrun_prev_compadd] )); then\n"
"        __jrun_prev_compadd \"${__jrun_args[@]}\"\n"
"    else\n"
"        builtin compadd \"${__jrun_args[@]}\"\n"
"    fi\n"
"}\n"
"\n";

